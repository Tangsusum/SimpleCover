# ─── 4. Task function ──────────────────────────────────────────────────────────
# Task function wired to: agent_client.invoke_agent (the app's single seam for
# calling the Bedrock Agent — reused as-is, only agent_id/alias_id vary).
#   source:  agent_client.py:138
#   purpose: compare current vs. previous model version on the same
#            tools/KB, so the only variable is the foundation model.
#   adapter: input_data may use any of "message"/"query"/"question"/"input"
#            for the customer's message and "customer_id" for the customer —
#            falls back to the first string value found if none match. The
#            exact keys in the "Insurance Usecases" dataset were not
#            inspected before generating this file (no live Datadog MCP
#            connection this session) — adjust the lookups below if the
#            dataset uses different field names.
VARIANTS: Dict[str, Dict[str, Any]] = {
    "current": {
        "agent_id": "8E99B3TGPA",
        "agent_alias_id": "LEQFZCRORY",
        "model_id": "au.anthropic.claude-sonnet-4-5-20250929-v1:0",
        "label": "sonnet-4.5-current",
    },
    "previous": {
        "agent_id": "UHAVD2GZVZ",
        "agent_alias_id": "G9HJW0BH89",
        "model_id": "apac.anthropic.claude-sonnet-4-20250514-v1:0",
        "label": "sonnet-4-previous",
    },
}

_MESSAGE_KEYS = ("message", "query", "question", "input", "text")


def _extract_message(input_data: Dict[str, Any]) -> str:
    for key in _MESSAGE_KEYS:
        if input_data.get(key):
            return str(input_data[key])
    for value in input_data.values():
        if isinstance(value, str) and value.strip():
            return value
    raise ValueError(f"Could not find a message field in input_data: {input_data!r}")


def task_fn(input_data: Dict[str, Any], config: Dict[str, Any]) -> Dict[str, Any]:
    variant = VARIANTS[config["variant"]]
    message = _extract_message(input_data)
    customer_id = str(input_data.get("customer_id", "experiment-customer"))
    # Deterministic per (variant, message) session id — no dataset record_id
    # is minted here, this is only a Bedrock conversation session id.
    session_id = "exp-" + hashlib.sha256(
        f"{config['variant']}:{customer_id}:{message}".encode()
    ).hexdigest()[:16]

    result = agent_client.invoke_agent(
        customer_id=customer_id,
        session_id=session_id,
        message=message,
        agent_id=variant["agent_id"],
        alias_id=variant["agent_alias_id"],
    )
    return {
        "response": result["response"],
        "trace": result["trace"],
        "model_id": variant["model_id"],
    }


# ─── 5. Evaluators ──────────────────────────────────────────────────────────────
def responded(input_data, output_data, expected_output) -> bool:
    return bool(output_data.get("response", "").strip())


def guardrail_clean(input_data, output_data, expected_output) -> EvaluatorResult:
    blocked = [
        t for t in output_data.get("trace", [])
        if t.get("kind") == "guardrail" and t.get("blocked")
    ]
    if blocked:
        return EvaluatorResult(
            value=False,
            reasoning=f"Guardrail intervened {len(blocked)} time(s) during this turn.",
            assessment="fail",
            metadata={"guardrail_events": blocked},
        )
    return EvaluatorResult(value=True, assessment="pass")


# TODO(user): review/tune this rubric before relying on the score. It grades
# the agent's reply against the customer's question only (no ground-truth
# expected_output assumed, since dataset schema wasn't inspected live). The
# judge runs on Bedrock using the CURRENT model for both variants' scoring —
# a single fixed judge model keeps the two variants' scores comparable.
answer_quality = LLMJudge(
    name="answer_quality",
    system_prompt=(
        "You are grading a health-insurance customer support reply for "
        "correctness and helpfulness. Be strict about factual contradictions."
    ),
    user_prompt=(
        "Customer question:\n{{input_data}}\n\n"
        "Agent reply:\n{{output_data}}\n\n"
        "Does the reply directly and correctly address the question using "
        "plausible health-insurance product facts (tiers, premiums, waiting "
        "periods, rebate/MLS/LHC) without contradicting itself?"
    ),
    structured_output=BooleanStructuredOutput(
        description="True if the reply correctly and helpfully answers the question.",
        reasoning=True,
        pass_when=True,
    ),
    provider="bedrock",
    model=VARIANTS["current"]["model_id"],
    client_options={"region_name": config.REGION},
)

# ─── 6. Experiments ─────────────────────────────────────────────────────────────
EVALUATORS = [responded, guardrail_clean, answer_quality]
JOBS = int(os.getenv("SIMPLE_COVER_EXPERIMENT_JOBS", "5"))

experiments = {}
