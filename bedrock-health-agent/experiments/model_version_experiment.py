# ─── 1. Env setup ─────────────────────────────────────────────────────────────
# Auto-discovers .env files at runtime. NO python-dotenv dependency.
# Discovery order (first non-empty value wins per key; shell env always
# overrides files): repo root .env(.local) -> cwd .env(.local) -> parent walk
# -> ~/.datadog/credentials. Export vars in your shell to override any file.
import pathlib


def _load_env_files(extra=None):
    here = pathlib.Path(__file__).resolve().parent
    repo_root = here.parent
    cwd = pathlib.Path.cwd().resolve()
    candidates = [pathlib.Path(p).expanduser() for p in (extra or [])]
    candidates += [
        repo_root / ".env", repo_root / ".env.local",
        here / ".env", here / ".env.local",
        cwd / ".env", cwd / ".env.local",
    ]
    p = cwd
    while p != p.parent and p != pathlib.Path.home().parent:
        candidates.append(p / ".env")
        p = p.parent
    candidates.append(pathlib.Path.home() / ".datadog" / "credentials")

    loaded, seen = [], set()
    for path in candidates:
        try:
            path = path.resolve()
        except Exception:
            continue
        if path in seen or not path.is_file():
            continue
        seen.add(path)
        try:
            text = path.read_text()
        except Exception:
            continue
        for line in text.splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            if line.startswith("export "):
                line = line[len("export "):]
            k, _, v = line.partition("=")
            k, v = k.strip(), v.strip().strip('"').strip("'")
            if k and k not in os.environ:
                os.environ[k] = v
        loaded.append(str(path))
    return loaded


